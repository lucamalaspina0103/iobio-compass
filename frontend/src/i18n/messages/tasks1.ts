// Chiavi: task.<area>.<numero da 0>. Ogni lingua deve avere 15 voci per area (lo verifica il test).

type Lists = { [area: string]: string[] };

export const flatten = (prefix: string, lists: Lists): Dict => {
  const out: Dict = {};
  for (const area of Object.keys(lists)) {
    lists[area].forEach((text, i) => {
      out[`${prefix}.${area}.${i}`] = text;
    });
  }
  return out;
};

